"""Stage 2D-1 internal wallet reservation engine. NO public/whitelisted routes.

Every mutation takes the Member and Wallet row locks, in that order. The
caller owns the database transaction; this module NEVER commits. Payment and
checkout integrations MUST only call settle after verifying actual payment.

Valid-through dates are inclusive. Reservation expiry uses server datetime.
Expired/released holds do not reduce available credits. Refunds restore credit
to original grants, preserving original expiry and employer provenance.
"""
import re
from collections import defaultdict
from contextlib import contextmanager
from datetime import timedelta
from decimal import Decimal

import frappe
from frappe.utils import getdate, get_datetime, now_datetime

from club100_core.wallet.core import get_or_create_wallet, _internal_ledger_post
from club100_core.wallet.logic import money, is_active
from club100_core.wallet.spending_logic import allocate, grant_net

KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9:_.-]{5,89}$")


def _key(raw, label):
    text = str(raw or '')
    if not KEY_RE.fullmatch(text):
        raise ValueError(f'{label} must be 6-90 URL-safe characters')
    return text


@contextmanager
def _internal_reservation_write():
    old = getattr(frappe.flags, 'club100_wallet_transaction', False)
    frappe.flags.club100_wallet_transaction = True
    try:
        yield
    finally:
        frappe.flags.club100_wallet_transaction = old


def _locked_wallet(member):
    """Always acquire Member lock first, matching grant creation lock order."""
    wallet = get_or_create_wallet(member)
    rows = frappe.db.sql("""SELECT name FROM `tabClub100 Wallet`
                            WHERE name=%s AND status='Active' FOR UPDATE""", (wallet,))
    if len(rows) != 1:
        frappe.throw('Wallet is not active')
    return wallet


def _snapshot(wallet, now):
    """Lock current rows, avoiding stale repeatable-read snapshots."""
    grants = frappe.db.sql("""SELECT name, source_type, member, wallet, amount,
                                   status, valid_from, validity_type, expires_on
                              FROM `tabClub100 Wallet Grant`
                             WHERE wallet=%s ORDER BY creation ASC FOR UPDATE""",
                           (wallet,), as_dict=True)
    ledger = frappe.db.sql("""SELECT `grant`, amount FROM `tabClub100 Wallet Ledger`
                             WHERE wallet=%s FOR UPDATE""", (wallet,), as_dict=True)
    holds = frappe.db.sql("""SELECT i.`grant`, i.amount
                              FROM `tabClub100 Wallet Reservation Item` i
                              JOIN `tabClub100 Wallet Reservation` r ON r.name=i.parent
                             WHERE r.wallet=%s AND r.status='Reserved'
                               AND r.expires_at > %s FOR UPDATE""",
                          (wallet, now), as_dict=True)
    reserved = defaultdict(lambda: Decimal('0.00'))
    for r in holds:
        reserved[r.grant] += money(r.amount)
    return grant_net(grants, ledger), reserved


def _result(doc):
    effective_status = ('Expired' if doc.status == 'Reserved'
                        and get_datetime(doc.expires_at) <= now_datetime() else doc.status)
    return {'reservation': doc.name, 'key': doc.reservation_key,
            'status': effective_status, 'amount': str(money(doc.total_amount)),
            'expires_at': str(doc.expires_at),
            'allocations': [{'grant': it.grant, 'source': it.source_type,
                             'amount': str(money(it.amount))} for it in doc.items]}


def reserve(member, reservation_key, reference, amount, ttl_minutes=15,
            allowed_sources=None, allowed_grants=None):
    """Trusted server-side call only. Does not expose credits to checkout yet.

    reservation_key must represent a unique business attempt, generated by
    server-side checkout. Replays must have identical member/reference/amount.
    """
    key = _key(reservation_key, 'Reservation key')
    ref = str(reference or '').strip()
    if not ref or len(ref) > 140:
        raise ValueError('Business reference required (maximum 140 characters)')
    total = money(amount)
    if total <= 0:
        raise ValueError('Reservation amount must be positive')
    ttl = int(ttl_minutes)
    if ttl < 1 or ttl > 60 or str(ttl) != str(ttl_minutes):
        raise ValueError('TTL must be an integer between 1 and 60 minutes')
    permitted = tuple(allowed_sources if allowed_sources is not None else ('Corporate', 'Referral', 'Promotion'))
    approved_grants = None if allowed_grants is None else frozenset(str(x) for x in allowed_grants)
    if approved_grants is not None and (not approved_grants or len(approved_grants) > 200):
        raise ValueError('Nonempty, bounded eligible-grant allowlist required')
    wallet = _locked_wallet(member)
    prior = frappe.db.get_value('Club100 Wallet Reservation', {'reservation_key': key}, 'name')
    if prior:
        doc = frappe.get_doc('Club100 Wallet Reservation', prior)
        if doc.member != member or doc.reference != ref or money(doc.total_amount) != total:
            raise ValueError('Reservation key already belongs to a different request')
        if any(it.source_type not in permitted for it in doc.items):
            raise ValueError('Reservation already uses a source prohibited by this request')
        if approved_grants is not None and any(it.grant not in approved_grants for it in doc.items):
            raise ValueError('Reservation already uses a grant outside the eligibility allowlist')
        return _result(doc)
    now = now_datetime()
    grants, held = _snapshot(wallet, now)
    # All ordinary callers retain their legacy allocation behavior. A hybrid
    # promotional reservation can explicitly exclude unapproved legacy grants.
    if approved_grants is not None:
        grants = [g for g in grants if g['name'] in approved_grants]
    selected = allocate(grants, held, total, getdate(now), permitted)
    with _internal_reservation_write():
        doc = frappe.get_doc({
            'doctype': 'Club100 Wallet Reservation',
            'reservation_key': key, 'member': member, 'wallet': wallet,
            'reference': ref, 'total_amount': total, 'currency': 'INR',
            'status': 'Reserved', 'expires_at': now + timedelta(minutes=ttl),
            'items': [{'grant': grant, 'source_type': source, 'amount': value}
                      for grant, source, value in selected],
        })
        doc.insert(ignore_permissions=True)
    return _result(doc)


def _locked_reservation(reservation_key):
    key = _key(reservation_key, 'Reservation key')
    # Get member to enforce consistent lock order across wallet operations.
    row = frappe.db.get_value('Club100 Wallet Reservation', {'reservation_key': key}, ['name', 'member'], as_dict=True)
    if not row:
        raise ValueError('Unknown reservation')
    wallet = _locked_wallet(row.member)
    locked = frappe.db.sql("""SELECT name FROM `tabClub100 Wallet Reservation`
                               WHERE name=%s AND wallet=%s FOR UPDATE""", (row.name, wallet))
    if not locked:
        raise ValueError('Reservation wallet mismatch')
    return frappe.get_doc('Club100 Wallet Reservation', row.name)


def _save_status(doc, status, timestamp_field=None):
    with _internal_reservation_write():
        doc.status = status
        if timestamp_field:
            doc.set(timestamp_field, now_datetime())
        doc.save(ignore_permissions=True)


def capture(reservation_key, verified_reference):
    """Trusted settlement step; checkout MUST verify full required payment first."""
    ref = str(verified_reference or '').strip()
    if not ref or len(ref) > 140:
        raise ValueError('Verified capture reference required')
    doc = _locked_reservation(reservation_key)
    if doc.status == 'Captured':
        if doc.reference != ref:
            raise ValueError('Capture replay has a different business reference')
        return _result(doc)
    if doc.status != 'Reserved':
        raise ValueError('Reservation cannot be captured in this state')
    now = now_datetime()
    if get_datetime(doc.expires_at) <= now:
        raise ValueError('Reservation expired; begin a new checkout attempt')
    if doc.reference != ref:
        raise ValueError('Capture reference differs from reservation')
    grants, held = _snapshot(doc.wallet, now)
    lookup = {g['name']: g for g in grants}
    for item in doc.items:
        g = lookup.get(item.grant)
        if not g or g['member'] != doc.member or g['wallet'] != doc.wallet:
            raise ValueError('Reservation grant does not belong to this wallet')
        if g['status'] != 'Active' or not is_active(g['valid_from'], g['validity_type'], g.get('expires_on'), getdate(now)):
            raise ValueError('Grant is no longer valid; cannot capture')
        if money(g['net']) < money(item.amount):
            raise ValueError('Grant funds no longer available')
        if money(held[item.grant]) < money(item.amount):
            raise ValueError('Reserved amount missing from active hold')
    with _internal_ledger_post():
        for item in doc.items:
            frappe.get_doc({
                'doctype': 'Club100 Wallet Ledger',
                'event_key': 'WALLET:SPEND:' + doc.name + ':' + item.grant,
                'wallet': doc.wallet, 'member': doc.member,
                'grant': item.grant, 'entry_type': 'Spend',
                'amount': -money(item.amount), 'currency': 'INR',
                'reference': doc.reference,
            }).insert(ignore_permissions=True)
    _save_status(doc, 'Captured', 'captured_at')
    return _result(doc)


def release(reservation_key):
    """Cancel an unused hold, or mark an elapsed hold Expired. No ledger debit."""
    doc = _locked_reservation(reservation_key)
    if doc.status in ('Released', 'Expired'):
        return _result(doc)
    if doc.status != 'Reserved':
        raise ValueError('Cannot release captured/refunded wallet reservation')
    status = 'Expired' if get_datetime(doc.expires_at) <= now_datetime() else 'Released'
    _save_status(doc, status, 'released_at')
    return _result(doc)


def refund_full(reservation_key):
    """Full wallet refund back to ORIGINAL grants. Partial refunds deferred.

    Expired grants are not revived. Repeat calls to a refunded reservation are
    idempotent. Caller is responsible for refund eligibility and accounting.
    """
    doc = _locked_reservation(reservation_key)
    if doc.status == 'Refunded':
        return _result(doc)
    if doc.status != 'Captured':
        raise ValueError('Only a captured reservation can be refunded')
    with _internal_ledger_post():
        for item in doc.items:
            frappe.get_doc({
                'doctype': 'Club100 Wallet Ledger',
                'event_key': 'WALLET:REFUND:' + doc.name + ':' + item.grant,
                'wallet': doc.wallet, 'member': doc.member, 'grant': item.grant,
                'entry_type': 'Refund', 'amount': money(item.amount),
                'currency': 'INR', 'reference': doc.reference,
            }).insert(ignore_permissions=True)
    _save_status(doc, 'Refunded', 'refunded_at')
    return _result(doc)


def wallet_spending_healthcheck():
    return {'site': frappe.local.site, 'doctypes': {
        dt: bool(frappe.db.exists('DocType', dt))
        for dt in ('Club100 Wallet Reservation', 'Club100 Wallet Reservation Item')},
        'reservations': frappe.db.count('Club100 Wallet Reservation') if frappe.db.exists('DocType', 'Club100 Wallet Reservation') else None,
        'checkout_spending_enabled': False, 'public_wallet_spend_apis': False,
        'refund_scope': 'Full wallet reversal only; returns to original grants',
        'automatic_cash_topups': False}
